from typing import Literal

from pydantic import BaseModel, Field


class TeachBackSource(BaseModel):
    page_index: int = Field(ge=0)
    source_line_index: int = Field(ge=0)
    source_quote: str = Field(min_length=1)


class ExplainedFact(BaseModel):
    fact_id: str = Field(min_length=1)
    label: str
    value: str | None = None
    explanation: str = Field(min_length=1)

    needs_review: bool = False
    review_reasons: list[str] = Field(default_factory=list)

    source: TeachBackSource


class TeachBackQuestion(BaseModel):
    question_id: str
    question: str
    fact_ids: list[str]


class TeachBackGenerateRequest(BaseModel):
    language: Literal["vi", "en", "ja"] = "vi"

    explanations: list[ExplainedFact] = Field(
        min_length=1,
        max_length=40,
    )

    question_count: int = Field(
        default=2,
        ge=1,
        le=3,
    )


class TeachBackEvaluateRequest(BaseModel):
    language: Literal["vi", "en", "ja"] = "vi"

    explanations: list[ExplainedFact] = Field(
        min_length=1,
        max_length=40,
    )

    question: TeachBackQuestion

    answer: str = Field(
        min_length=1,
        max_length=2000,
    )


# Structured outputs generated by Gemini.

class GeneratedQuestionDraft(BaseModel):
    question: str
    fact_ids: list[str]


class TeachBackGenerateDraft(BaseModel):
    questions: list[GeneratedQuestionDraft]


class TeachBackEvaluationDraft(BaseModel):
    assessment: Literal[
        "understood",
        "partially_understood",
        "needs_clarification",
        "not_assessable",
    ]

    feedback: str
    clarification: str | None = None

    supporting_fact_ids: list[str]